"""Operator actions for independent, private network-role guests."""
from __future__ import annotations

import hashlib
import importlib
from pathlib import Path
import secrets
import time

from .contracts import ApplianceError, canonical, identity, load_json, require
from . import state

ROLES = ('connector', 'headscale', 'derp')
CAPABILITIES = {'enrollment': 'connector', 'controller': 'headscale', 'relay': 'derp'}


def add_commands(commands):
    roles = commands.add_parser('roles', help='Join a network or manage optional controller and relay guests')
    sub = roles.add_subparsers(dest='action', required=True)
    for name in ('inspect', 'eligibility'): sub.add_parser(name)
    prepare = sub.add_parser('provision', help='Import a pinned role image, stopped and disconnected')
    prepare.add_argument('role', choices=ROLES)
    prepare.add_argument('--inputs', type=Path, required=True)
    prepare.add_argument('--image-receipt', type=Path,
                         help='Private receipt generated by the local role-image builder')
    for name in ('start', 'reconcile-vm'):
        cmd = sub.add_parser(name); cmd.add_argument('role', choices=ROLES)
    join = sub.add_parser('join', help='Use a private owner-approved single-use enrollment file')
    join.add_argument('--authorization', type=Path, required=True)
    for name in ('create-controller', 'configure-relay'):
        cmd = sub.add_parser(name)
        cmd.add_argument('--credentials', type=Path, required=True)
    for name in ('approve-client', 'set-verification-policy'):
        cmd = sub.add_parser(name); cmd.add_argument('--request-file', type=Path, required=True)
    key = sub.add_parser('register-probe', help='Register the independently obtained probe public key')
    key.add_argument('--public-key', type=Path, required=True)
    probe = sub.add_parser('probe-request', help='Create a fresh, locally bound external test challenge')
    probe.add_argument('capability', choices=tuple(CAPABILITIES))
    probe.add_argument('--targets', type=Path, required=True)
    probe.add_argument('--output', type=Path, required=True)
    verify = sub.add_parser('verify-probe', help='Verify a signed reply to a locally generated challenge')
    verify.add_argument('--receipt', type=Path, required=True)
    query = sub.add_parser('query-operation', help='Inspect an uncertain operation without repeating it')
    query.add_argument('role', choices=ROLES); query.add_argument('operation_id')


def _guest(plan, role, runner, private, *, reconnect=False):
    module = importlib.import_module('appliance.' + role)
    observed = module.inspect(plan, runner, private, reconnect=reconnect)
    return observed.get('observations', {}) if role == 'connector' else observed


def _router_ready(plan, runner):
    from .router import collect_router, router_ready
    observed = collect_router(plan, runner)
    require(router_ready(plan, observed).get('checks_passed') is True, 'role-router-not-ready')
    require(observed.get('stage') == 'transit', 'role-router-transit-required')
    return observed


def start_role(plan, role, runner, private):
    from . import guests
    require(role in ROLES and plan['roles'][role]['selected'], 'role-not-selected')
    _router_ready(plan, runner)
    guests.start_linux(plan, role, runner, private)
    guests.inspect_runtime(plan, role, runner, private)
    guests.set_linux_link(plan, role, True, runner, private)
    try:
        observed = _guest(plan, role, runner, private, reconnect=True)
    except ApplianceError as error:
        # A first start deliberately has no authority or enrollment credential.
        if error.code not in ('connector-not-enrolled', 'headscale-not-configured',
                              'derp-not-configured', 'hosting-not-configured', 'state-file-missing'):
            raise
        return {'role': role, 'state': 'prepared', 'code': error.code,
                'next_action': 'Use the explicit join, create-controller or configure-relay action.'}
    return {'role': role, 'state': 'configured' if observed.get('configured') or observed.get('registered') else 'prepared',
            'next_action': 'Run a fresh independent probe; reconnection does not verify public reachability.'}


def _context(plan, role, runner, private, observed=None):
    from .guests import observe_linux
    guest = observe_linux(plan, role, runner, private)
    router = _router_ready(plan, runner)
    observed = _guest(plan, role, runner, private) if observed is None else observed
    role_identity = observed.get('identity', observed.get('node_id'))
    require(role_identity is not None, 'role-identity-unavailable')
    return {'role_identity': role_identity, 'config': observed.get('config_id', identity(plan['roles'][role])),
            'policy': observed.get('policy_id', identity({'role': role, 'policy_matches': observed.get('policy_matches')})),
            'certificate': observed.get('certificate_id', observed.get('tls_sha256', 'none')),
            'guest_boot': identity({'boot': guest.get('boot_id'), 'guest_boot': observed.get('boot_id'),
                                    'config': guest.get('config')}),
            'router_boot': identity({'boot': router.get('boot_id'), 'vm_boot': router.get('vm_boot_id'),
                                     'config': router.get('config_digest'), 'xml': router.get('config_xml')})}


def _trusted_proof(plan, staged, capability, receipt, runner, private, *, observed=None):
    from .probes import verify_probe
    nonce = receipt.get('nonce')
    require(type(nonce) is str and len(nonce) == 64 and all(c in '0123456789abcdef' for c in nonce),
            'probe-challenge-unknown')
    saved = state.read(Path(private) / 'probe-requests' / (nonce + '.json'))
    request = saved['request']
    require(request['capability'] == capability and request['plan_id'] == identity(plan) and
            request['build_id'] == staged['build_id'] and request['probe'] == plan.get('probe_endpoint'),
            'probe-challenge-stale')
    require(saved['context'] == _context(plan, CAPABILITIES[capability], runner, private, observed),
            'probe-runtime-changed')
    return verify_probe(request, receipt, Path(private) / 'probe-public.pem', runner, now=int(time.time()))


def role_status(plan, staged, runner, private):
    from .hosting import eligibility
    result = {}
    for role in ROLES:
        if not plan['roles'][role]['selected']:
            result[role] = {'state': 'not-selected'}
            continue
        try:
            observed = _guest(plan, role, runner, private)
            capability = next(k for k, v in CAPABILITIES.items() if v == role)
            proof_path = Path(private) / 'probe-receipts' / (capability + '.json')
            proof = (_trusted_proof(plan, staged, capability, state.read(proof_path), runner, private,
                                    observed=observed) if proof_path.exists() else {})
            if role == 'connector':
                result[role] = {'state': 'verified' if proof.get('state') == 'verified' and observed.get('registered') is True else
                               ('configured' if observed.get('registered') else 'unknown'),
                               'next_action': 'Repeat independent allow, deny and relay tests after changes.'}
            else:
                result[role] = eligibility(plan, {'guest': observed, 'probe_evidence': proof}, role)
        except ApplianceError as error:
            result[role] = {'state': 'unknown', 'code': error.code,
                            'next_action': 'Inspect the guest and repeat the affected checks; its identity is retained.'}
    return result


def execute(args, plan, release, staged, runner, private):
    from . import guests
    private = Path(private)
    if args.action in ('inspect', 'eligibility'):
        if args.action == 'eligibility':
            from .hosting import eligibility
            roles = {r: eligibility(plan, {}, r) for r in ('headscale', 'derp')}
        else:
            roles = role_status(plan, staged, runner, private)
        return {'state': 'inspected', 'roles': roles, 'qualification': 'not-run'}
    if args.action == 'provision':
        require(plan['roles'][args.role]['selected'], 'role-not-selected')
        guests.provision_linux(plan, args.role, runner, private, release=release, inputs=args.inputs,
                               image_receipt=args.image_receipt)
        return {'state': 'prepared', 'role': args.role, 'running': False, 'connected': False}
    if args.action == 'start': return start_role(plan, args.role, runner, private)
    if args.action == 'reconcile-vm':
        guests.reconcile_linux(plan['vms'][args.role]['vmid'], runner, private)
        return {'state': 'inspected', 'role': args.role}
    if args.action == 'join':
        from .connector import join
        return join(plan, state.read(args.authorization), runner, private)
    if args.action in ('create-controller', 'configure-relay'):
        if args.action == 'create-controller':
            from .headscale import create_authority as configure
        else:
            from .derp import configure_relay as configure
        return configure(plan, state.read(args.credentials), runner, private)
    if args.action in ('approve-client', 'set-verification-policy'):
        from . import headscale
        function = headscale.approve_client if args.action == 'approve-client' else headscale.set_verification_policy
        return function(plan, state.read(args.request_file), runner, private)
    if args.action == 'query-operation':
        request = {'schema': 1, 'operation_id': args.operation_id, 'plan_id': identity(plan),
                   'role': args.role, 'action': 'inspect', 'parameters': {'query_operation': True}}
        reply = guests.query_guest_operation(plan['vms'][args.role]['vmid'], request, runner, state=private)
        return {'state': 'inspected', 'operation_id': reply['operation_id'], 'phase': reply['phase'], 'code': reply['code']}
    if args.action == 'register-probe':
        from .probes import _key
        key = _key(args.public_key)
        require(hashlib.sha256(key).hexdigest() == plan.get('probe_endpoint', {}).get('key_sha256'),
                'probe-key-not-registered')
        target = private / 'probe-public.pem'
        from .export import _private_bytes
        if target.exists(): require(_private_bytes(target, 16384) == key, 'probe-key-change-refused')
        else:
            with state._directory_fd(private) as fd: state._write_at(fd, target.name, key)
        return {'state': 'registered', 'probe_id': plan['probe_endpoint']['id']}
    if args.action == 'probe-request':
        from .probes import make_probe
        from .operations import _new_file
        role = CAPABILITIES[args.capability]
        context = _context(plan, role, runner, private)
        targets = load_json(args.targets)['targets']
        request = make_probe(plan, staged['build_id'], args.capability, targets,
                             now=int(time.time()), dependencies=context)
        state.write(private / 'probe-requests' / (request['nonce'] + '.json'), {'request': request, 'context': context})
        _new_file(args.output, canonical(request))
        return {'state': 'prepared', 'challenge_file': str(args.output), 'expires_at': request['expires_at'],
                'next_action': 'Run this challenge on the registered independent endpoint.'}
    if args.action == 'verify-probe':
        receipt = load_json(args.receipt, limit=512 * 1024)
        capability = receipt.get('capability')
        require(capability in CAPABILITIES, 'probe-capability-invalid')
        observed = _guest(plan, CAPABILITIES[capability], runner, private)
        proof = _trusted_proof(plan, staged, capability, receipt, runner, private, observed=observed)
        if proof['state'] == 'verified':
            state.write(private / 'probe-receipts' / (capability + '.json'), receipt)
        if capability != 'enrollment':
            from .hosting import eligibility
            return eligibility(plan, {'guest': observed, 'probe_evidence': proof}, CAPABILITIES[capability])
        if observed.get('registered') is not True and proof['state'] == 'verified':
            proof.update(state='unknown', next_action='Reconnect and inspect the existing connector identity.')
        return proof
    raise ApplianceError('unsupported-role-action')
